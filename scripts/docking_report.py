"""Merge the per-receptor docking benchmarks into one table and figure (W3).

Reads eval/docking_benchmark_*.json, applies the rules pre-registered in docs/preregistration.md
(a receptor/oracle pair is usable for ranking only if its ROC AUC 95% CI lower bound exceeds 0.5;
a second scoring function is adopted only where the paired AUC difference interval excludes 0),
and writes:

  eval/docking_benchmark.json        canonical, machine-readable, consumed by the docking agent
  docs/docking_validation_table.md   the table every document quotes
  figures/docking_benchmark.png      AUC with intervals, and the score gap that explains them
"""
from __future__ import annotations

import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def style():
    import matplotlib as mpl
    mpl.rcParams.update({
        "figure.dpi": 110, "savefig.dpi": 200, "font.size": 8.5, "axes.titlesize": 9,
        "axes.labelsize": 8.5, "xtick.labelsize": 7.5, "ytick.labelsize": 7.5,
        "legend.fontsize": 7.5, "axes.spines.top": False, "axes.spines.right": False,
        "axes.edgecolor": "#444444", "axes.linewidth": 0.8, "text.color": "#141821",
        "figure.facecolor": "white", "savefig.facecolor": "white"})


def collect():
    receptors = []
    for path in sorted(glob.glob(os.path.join(HERE, "eval", "docking_benchmark_*.json"))):
        with open(path, encoding="utf-8") as fh:
            blob = json.load(fh)
        for rec in blob.get("receptors", []):
            rec["_source_file"] = os.path.basename(path)
            rec["_vina_binary"] = blob.get("vina_binary")
            receptors.append(rec)
    order = {"8A27": 0, "1M17": 1, "1OYT": 2}
    receptors.sort(key=lambda r: order.get(r["pdb"], 9))
    return receptors


def main() -> int:
    receptors = collect()
    if not receptors:
        print("no eval/docking_benchmark_*.json found", file=sys.stderr)
        return 1

    usable, adopted = [], []
    for r in receptors:
        for name, sc in r["scoring"].items():
            if sc["auc_ci95"][0] > 0.5:
                usable.append(f"{r['pdb']}/{name}")
        d = r.get("delta_auc_vinardo_minus_vina") or {}
        if d.get("excludes_zero") and d.get("mean", 0) > 0:
            adopted.append(r["pdb"])

    out = {
        "generated_by": "scripts/docking_report.py",
        "criterion": "docs/preregistration.md W3",
        "n_receptors": len(receptors),
        "usable_for_ranking": usable,
        "vinardo_adopted_on": adopted,
        "receptors": [{k: v for k, v in r.items() if k != "rows"} for r in receptors],
    }
    with open(os.path.join(HERE, "eval", "docking_benchmark.json"), "w", encoding="utf-8") as fh:
        json.dump(out, fh, indent=1)

    lines = ["# Retrospective docking validation, per receptor and per scoring function",
             "",
             "Generated by `scripts/docking_report.py` from `eval/docking_benchmark_*.json`. Do not",
             "edit: quote it. Decoys are **measured inactives** (a molecule with no measurement is",
             "not an inactive), property-matched to the actives on MW and cLogP. Criterion:",
             "`docs/preregistration.md` W3.", "",
             "| receptor | family | ligand source | actives | decoys | oracle | ROC AUC | 95% CI |"
             " EF 10% | score gap (kcal/mol) | usable for ranking |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in receptors:
        for name, sc in r["scoring"].items():
            src = "ChEMBL" if "ChEMBL" in (r.get("ligand_source") or "") else "PubChem BioAssay"
            lines.append(
                f"| {r['pdb']} | {r['family']} | {src} | {r['n_actives']} | {r['n_decoys']} | "
                f"{name} | {sc['roc_auc']:.3f} | [{sc['auc_ci95'][0]:.3f}, "
                f"{sc['auc_ci95'][1]:.3f}] | {sc['ef_10pct']} | {sc['score_gap']:+.3f} | "
                f"{'yes' if sc['usable_for_ranking'] else 'no'} |")
    lines += ["", "Paired bootstrap, Vinardo minus Vina, same ligands and same box:", ""]
    for r in receptors:
        d = r.get("delta_auc_vinardo_minus_vina") or {}
        if d:
            lines.append(f"* **{r['pdb']}**: {d['mean']:+.3f} "
                         f"[{d['ci95'][0]:+.3f}, {d['ci95'][1]:+.3f}] — "
                         f"{'excludes 0' if d['excludes_zero'] else 'includes 0, no measured gain'}")
    lines += ["",
              f"Usable for ranking by the pre-registered rule: "
              f"{', '.join(usable) if usable else 'none'}.",
              f"Vinardo adopted on: {', '.join(adopted) if adopted else 'no receptor'}.",
              "",
              "A positive score gap means the decoys scored *better* than the actives: on that",
              "receptor the oracle's ordering is inverted, not merely uninformative."]
    with open(os.path.join(HERE, "docs", "docking_validation_table.md"), "w",
              encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import numpy as np
    style()
    fig, axs = plt.subplots(1, 2, figsize=(10.6, 3.6))
    ax = axs[0]
    labels, ys = [], []
    for i, r in enumerate(receptors):
        for j, (name, sc) in enumerate(r["scoring"].items()):
            y = i * 2.4 + (0 if name == "vina" else 0.9)
            colour = "#2b6cb0" if name == "vina" else "#e0803a"
            lo, hi = sc["auc_ci95"]
            ax.plot([lo, hi], [y, y], color=colour, lw=1.6, solid_capstyle="butt")
            ax.plot(sc["roc_auc"], y, "o", color=colour, ms=5.5,
                    mfc=colour if sc["usable_for_ranking"] else "white", mew=1.4)
            labels.append((y, f"{r['pdb']} · {name}"))
            ys.append(y)
    ax.axvline(0.5, color="#888", ls="--", lw=0.9)
    ax.text(0.515, max(ys) + 0.62, "chance", fontsize=7, color="#666")
    ax.set_yticks([y for y, _ in labels])
    ax.set_yticklabels([t for _, t in labels], fontsize=7.5)
    ax.set_xlim(0, 1)
    ax.set_xlabel("ROC AUC on measured inactives (95% bootstrap CI)")
    ax.set_title("One receptor/oracle pair clears chance")
    ax.invert_yaxis()

    ax = axs[1]
    names = [r["pdb"] for r in receptors]
    x = np.arange(len(names))
    w = 0.38
    for k, (name, colour) in enumerate((("vina", "#2b6cb0"), ("vinardo", "#e0803a"))):
        vals = [r["scoring"].get(name, {}).get("score_gap", 0.0) for r in receptors]
        ax.bar(x + (k - 0.5) * w, vals, width=w, color=colour, label=name)
        for xi, v in zip(x + (k - 0.5) * w, vals):
            ax.text(xi, v + (0.02 if v >= 0 else -0.06), f"{v:+.2f}", ha="center", fontsize=7)
    ax.axhline(0, color="#444", lw=0.8)
    ax.set_xticks(x)
    ax.set_xticklabels([f"{r['pdb']}\n{r['family']}" for r in receptors], fontsize=7)
    ax.set_ylabel("mean decoy score − mean active score")
    ax.legend(frameon=False, fontsize=7.5)
    ax.set_title("Positive bar = the ordering is inverted")

    fig.text(0.004, 0.025,
             "Actives: measured pChEMBL (or PubChem pAct) >= 7.0. Decoys: measured inactives "
             "<= 5.0, property-matched on MW and cLogP. Same box, same seed, exhaustiveness 8; "
             "filled marker = usable for ranking under the pre-registered rule\n"
             "(docs/preregistration.md W3). Counts and sources: "
             "docs/docking_validation_table.md.",
             fontsize=6.3, color="#666", linespacing=1.5)
    fig.tight_layout(rect=(0, 0.085, 1, 1))
    fig.savefig(os.path.join(HERE, "figures", "docking_benchmark.png"), dpi=200)
    print(f"receptors={len(receptors)} usable={usable} vinardo_adopted={adopted}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
